/**
 * Convertit un code ISO 3166-1 alpha-2 (ex. "GA") en emoji drapeau (🇬🇦)
 * en combinant les deux "regional indicator symbols" Unicode correspondants.
 * Même logique que le filtre Twig `country_flag` côté serveur.
 */
export function flagEmoji(code) {
    if (typeof code !== 'string' || code.length !== 2) {
        return '';
    }

    return code
        .toUpperCase()
        .replace(/./g, (letter) => String.fromCodePoint(127397 + letter.charCodeAt(0)));
}
